import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { expect, test, type Page } from "@playwright/test";
import { DEMO_SEED_PASSWORD } from "@/modules/settings/application/demo-seed-service";
import { getDatabaseClient } from "@/shared/core/database/client";
import { workspaceDateAt } from "@/shared/core/time/workspace-time";
import { enterDemoCompany } from "./helpers/company-hub";

async function login(page: Page, email: string) {
  await page.goto("/login");
  await page.getByLabel("E-mail").fill(email);
  await page.getByLabel("Senha").fill(DEMO_SEED_PASSWORD);
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await enterDemoCompany(page);
}

test("venda confirmada atualiza OTE aberto: 18 mil, entrada de 3 mil e 10 parcelas, com isolamento", async ({ page }, testInfo) => {
  if (!/^politizai_test_/.test(new URL(process.env.DATABASE_URL!).searchParams.get("schema") ?? "")) throw new Error("Banco temporário obrigatório.");
  const db = getDatabaseClient();
  const workspace = await db.workspace.findUniqueOrThrow({ where: { slug: "politizai" } });
  await db.$executeRawUnsafe(readFileSync("scripts/sql/configure-politizai-sales.sql", "utf8"));
  await db.$executeRawUnsafe(readFileSync("scripts/sql/configure-politizai-closer-sales.sql", "utf8"));
  const seller = await db.workspaceMember.findFirstOrThrow({ where: { workspaceId: workspace.id, user: { normalizedEmail: "closer1@demo.politizai.local" } } });
  const admin = await db.workspaceMember.findFirstOrThrow({ where: { workspaceId: workspace.id, user: { normalizedEmail: "admin@demo.politizai.local" } } });
  const actor = await db.actor.findFirstOrThrow({ where: { workspaceId: workspace.id, userId: admin.userId, type: "HUMAN" } });
  const month = workspaceDateAt(new Date(), workspace.timeZone).slice(0, 7);
  await db.otePlan.create({ data: { workspaceId: workspace.id, memberId: seller.id, effectiveMonth: month, label: "Sênior sintético", role: "CLOSER", fixedCents: 370000n, quotaCents: 6000000n, bonusCents: 120000n, meetingQuota: 20, salesQuota: 4, updatedByActorId: actor.id } });
  await login(page, "admin@demo.politizai.local");
  const name = `Cliente OTE automático ${randomUUID().slice(0, 8)}`;
  await page.goto("/leads/entrada");
  await page.getByLabel("Nome", { exact: true }).fill(name);
  await page.getByLabel("Telefone", { exact: true }).fill(`+55119${String(Date.now()).slice(-8)}`);
  await page.getByLabel("Cargo ou atuação").fill("Diretor");
  await page.getByLabel("Dor ou interesse").fill("Contratar Sistema Politizai");
  await page.getByRole("button", { name: "Cadastrar lead" }).click();
  await expect(page.getByText("Entrada processada", { exact: true })).toBeVisible();
  const lead = await db.lead.findFirstOrThrow({ where: { workspaceId: workspace.id, fullName: name } });
  await db.lead.update({ where: { id: lead.id }, data: { ownerMemberId: seller.id } });
  await page.context().clearCookies();
  await login(page, "closer1@demo.politizai.local");
  const ote = await page.context().newPage();
  await ote.goto(`/ote?month=${month}`);
  await expect(ote.getByRole("heading", { name: "Minha remuneração acumulada no mês" })).toBeVisible();
  const before = await ote.request.get(`/api/ote?month=${month}`);
  expect((await before.json()).result.summary.totalCents).toBe("370000");
  await page.bringToFront();
  await page.goto(`/leads/${lead.id}/historico`);
  await page.locator('[aria-label="Ações comerciais do lead"]').getByRole("button", { name: "Marcar vendido", exact: true }).click();
  const form = page.getByRole("tabpanel", { name: "Marcar vendido" });
  await form.getByRole("combobox", { name: "Vendedor", exact: true }).selectOption(seller.id);
  await form.getByLabel("Valor total (R$)", { exact: true }).fill("18.000,00");
  await form.getByRole("combobox", { name: "Condição de pagamento", exact: true }).selectOption("UPFRONT_INSTALLMENTS");
  await form.getByLabel("Entrada (R$)", { exact: true }).fill("3.000,00");
  await form.getByLabel("Valor de cada parcela (R$)").fill("1.500,00");
  await form.getByLabel("Condição de pagamento detalhada").fill("Entrada de R$ 3.000 e 10 parcelas de R$ 1.500 no PIX.");
  const response = page.waitForResponse((res) => res.url().endsWith("/api/opportunities/close-sale") && res.request().postDataJSON()?.action === "COMPLETE_LEAD");
  await form.getByRole("button", { name: "Confirmar e marcar vendido" }).click();
  const saved = await response;
  expect(await saved.json()).toMatchObject({ result: { receivedCents: "0", outstandingCents: "1800000" } });
  expect(saved.ok()).toBe(true);
  await ote.bringToFront();
  await ote.evaluate(() => window.dispatchEvent(new Event("focus")));
  await expect(ote.locator("main")).toContainText(/4\.780,00/);
  await expect(ote.locator("main")).toContainText(/1\.080,00/);
  await expect(ote.locator("main")).toContainText("10 parcela(s) de");
  await expect(ote.locator("main")).toContainText("PIX");
  const after = (await (await ote.request.get(`/api/ote?month=${month}`)).json()).result;
  expect(after.summary).toMatchObject({ newAcvCents: "1800000", commissionCents: "108000", totalCents: "478000", saleCount: 1, eligibleCents: "0" });
  expect(after.sales[0]).toMatchObject({ source: "AUTOMATIC", receivedCents: "0", terms: { upfrontCents: "300000", installmentCents: "150000", installmentCount: 10 } });
  expect(await db.oteSale.count({ where: { workspaceId: workspace.id, opportunityId: after.sales[0].id } })).toBe(0);
  await ote.screenshot({ path: testInfo.outputPath("ote-venda-automatica.png"), fullPage: true });
  await ote.close();
  await page.context().clearCookies();
  await login(page, "closer2@demo.politizai.local");
  const other = (await (await page.request.get(`/api/ote?month=${month}`)).json()).result;
  expect(JSON.stringify(other)).not.toContain(name);
  expect(other.plan).toBeNull();
});
